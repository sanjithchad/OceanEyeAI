"""Persistence adapter used by the simulator and API routes."""
from datetime import datetime, timezone
from sqlalchemy import select, desc
from sqlalchemy.orm import Session
from app.database.sqlalchemy_db import SessionLocal
from app.models.database_models import SensorReading, Device, Alert, Prediction, AIAnalysis

def parse_dt(value):
    if value is None: return None
    dt = datetime.fromisoformat(value.replace("Z", "+00:00")) if isinstance(value, str) else value
    return dt.replace(tzinfo=timezone.utc) if dt.tzinfo is None else dt.astimezone(timezone.utc)

def save_simulated_reading(reading: dict, device_name: str) -> None:
    """Upsert device heartbeat and append one immutable reading + generated alerts."""
    now = parse_dt(reading["timestamp"])
    with SessionLocal() as db:
        device = db.get(Device, reading["device_id"])
        if device is None:
            device = Device(id=reading["device_id"], device_name=device_name)
            db.add(device)
        device.device_name = device_name
        device.device_status = reading.get("sensor_status", "online")
        device.battery_level = float(reading.get("battery_level", 100.0))
        device.last_seen = now
        db.add(SensorReading(
            device_id=reading["device_id"], temperature=reading.get("temperature"),
            turbidity=reading.get("turbidity"), latitude=reading["latitude"],
            longitude=reading["longitude"], timestamp=now,
        ))
        for alert_type in reading.get("alerts", []):
            severity = "critical" if "DISCONNECTION" in alert_type else "high"
            db.add(Alert(alert_type=alert_type, severity=severity,
                         description=f"{alert_type.replace('_', ' ').title()} generated by {reading['device_id']} (SIMULATED).",
                         timestamp=now, resolved=False))
        db.commit()

def list_readings(db: Session, limit=100, start=None, end=None, device_id=None):
    stmt = select(SensorReading).order_by(desc(SensorReading.timestamp), desc(SensorReading.id)).limit(limit)
    if start is not None: stmt = stmt.where(SensorReading.timestamp >= start)
    if end is not None: stmt = stmt.where(SensorReading.timestamp <= end)
    if device_id: stmt = stmt.where(SensorReading.device_id == device_id)
    return list(db.scalars(stmt).all())


def save_prediction(prediction: dict) -> int:
    """Persist one model prediction; prediction_time must be an ISO-8601 string or datetime."""
    with SessionLocal() as db:
        item = Prediction(
            prediction_type=prediction["prediction_type"],
            predicted_value=str(prediction["predicted_value"]),
            prediction_time=parse_dt(prediction["prediction_time"]),
            confidence=float(prediction["confidence"]),
        )
        if not 0.0 <= item.confidence <= 1.0:
            raise ValueError("confidence must be between 0 and 1")
        db.add(item); db.commit(); db.refresh(item)
        return item.id

def save_ai_analysis(analysis: dict) -> int:
    """Persist one AI analysis result."""
    with SessionLocal() as db:
        item = AIAnalysis(analysis_type=analysis["analysis_type"], result=analysis["result"],
                          severity=analysis["severity"])
        db.add(item); db.commit(); db.refresh(item)
        return item.id

def save_alert(alert: dict) -> int:
    """Persist an alert emitted by a future rules/AI engine."""
    with SessionLocal() as db:
        item = Alert(alert_type=alert["alert_type"], severity=alert["severity"],
                     description=alert["description"], resolved=bool(alert.get("resolved", False)),
                     timestamp=parse_dt(alert["timestamp"]) if alert.get("timestamp") else datetime.now(timezone.utc))
        db.add(item); db.commit(); db.refresh(item)
        return item.id
