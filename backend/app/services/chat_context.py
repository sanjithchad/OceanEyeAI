"""Verified data context builder for the Ocean Eye AI chatbot."""

from ai_engine.analyzer import fetch_readings, analyze_sensor_data
from ai_engine.anomaly import detect_anomalies
from ai_engine.trends import analyze_trends
from ai_engine.forecast import generate_prediction
from ai_engine.risk import get_current_assessment


async def build_chat_context():
    """Collect verified application data for chatbot responses."""

    # Fetch stored readings once and reuse them consistently.
    all_readings = fetch_readings(limit=500)
    recent_readings = all_readings[-10:]
    latest = recent_readings[-1] if recent_readings else None

    # Phase 5: analysis, trends and anomaly detection.
    analysis = analyze_sensor_data(all_readings)
    trends = analyze_trends(all_readings)
    anomalies = detect_anomalies(all_readings)

    # Phase 6: experimental 24-hour temperature prediction.
    prediction = generate_prediction("24hours")

    # Phase 7: environmental risk assessment.
    risk = await get_current_assessment()

    return {
        "project": "Ocean Eye AI",
        "assistant": "Ocean Eye AI Assistant",

        "data_source": {
            "type": "simulated_demonstration_data",
            "description": (
                "Readings are generated by the Ocean Eye AI "
                "software simulator. They are not verified live "
                "ocean measurements."
            ),
        },

        "current_measurements": {
            "temperature_c": latest.get("temperature") if latest else None,
            "turbidity_ntu": latest.get("turbidity") if latest else None,
            "timestamp": latest.get("timestamp") if latest else None,
            "device_id": latest.get("device_id") if latest else None,
            "reading_id": latest.get("id") if latest else None,
        },

        "total_stored_readings": len(all_readings),
        "recent_sensor_history": recent_readings,
        "statistical_analysis": analysis,
        "historical_trends": trends,
        "anomaly_detection": anomalies,
        "environmental_risk": risk,
        "temperature_prediction_24_hours": prediction,

        "interpretation_rules": [
            "Never invent missing sensor measurements.",
            "Distinguish observed readings from predicted values.",
            "Identify simulator readings as synthetic demonstration data.",
            "Describe predictions as experimental, not guaranteed.",
            "Do not claim temperature or turbidity alone proves pollution.",
            "Describe risk scores as prototype indicators, not certified measurements.",
            "Explain when data is unavailable or incomplete.",
        ],
    }